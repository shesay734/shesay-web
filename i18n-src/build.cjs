// Builds ../i18n.js from en.json and one JSON array per language (same order
// as en.json). Run: node i18n-src/build.cjs
const fs = require('node:fs');
const path = require('node:path');

const dir = __dirname;
const languages = ['es', 'fr', 'it', 'zh', 'de', 'pt', 'ja'];
const en = JSON.parse(fs.readFileSync(path.join(dir, 'en.json'), 'utf8'));
const strings = { en };
for (const lang of languages) {
  const list = JSON.parse(fs.readFileSync(path.join(dir, `${lang}.json`), 'utf8'));
  if (list.length !== en.length) {
    throw new Error(`${lang}.json has ${list.length} entries; en.json has ${en.length}`);
  }
  strings[lang] = list;
}
const templates = JSON.parse(fs.readFileSync(path.join(dir, 'templates.json'), 'utf8'));
for (const entry of templates) {
  for (const lang of languages) {
    if (typeof entry[lang] !== 'string') throw new Error(`template "${entry.en}" lacks ${lang}`);
  }
}
const engine = fs.readFileSync(path.join(dir, 'engine.js'), 'utf8');
const out = `// Generated by i18n-src/build.cjs — edit the files in i18n-src instead.\n` +
  `window.SheSayI18nData = ${JSON.stringify({ strings, templates })};\n${engine}`;
fs.writeFileSync(path.join(dir, '..', 'i18n.js'), out);
console.log(`i18n.js: ${en.length} strings, ${templates.length} templates, ${languages.length + 1} languages`);
